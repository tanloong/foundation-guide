def exists(topic: str) -> bool:
    return topic.upper() in ENTRIES


def find(topic: str) -> str | None:
    """Find an entry by exact key or a forgiving substring match."""
    key = topic.strip().upper()
    if key in ENTRIES:
        return key
    # exact ignoring punctuation
    normalised = " ".join(key.replace("'", "").replace("-", " ").split())
    for candidate in ENTRIES:
        c = " ".join(candidate.replace("'", "").replace("-", " ").split())
        if normalised == c:
            return candidate
    # substring / token overlap
    matches = [c for c in ENTRIES if normalised and (normalised in c.lower() or c.lower() in normalised)]
    if len(matches) == 1:
        return matches[0]
    if matches:
        return sorted(matches, key=len, reverse=True)[0]
    return None
